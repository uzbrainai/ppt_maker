// Admin i18n: uz / ru / en. Kept in one file so translators can see all three
// versions side by side. Language is stored in localStorage and broadcast via a
// window event so every subscriber re-renders when the user switches.

export type Lang = 'uz' | 'ru' | 'en'

const KEY_LANG = 'pptadmin-lang'
const EVT = 'pptadmin:lang'

export const LANGS: { id: Lang; label: string; flag: string }[] = [
  { id: 'uz', label: "O'zbekcha", flag: '🇺🇿' },
  { id: 'ru', label: 'Русский', flag: '🇷🇺' },
  { id: 'en', label: 'English', flag: '🇬🇧' },
]

export function getStoredLang(): Lang {
  try {
    const v = localStorage.getItem(KEY_LANG) as Lang | null
    if (v && ['uz', 'ru', 'en'].includes(v)) return v
  } catch {}
  const nav = typeof navigator !== 'undefined' ? navigator.language.slice(0, 2).toLowerCase() : 'en'
  if (nav === 'uz') return 'uz'
  if (nav === 'ru') return 'ru'
  return 'en'
}

export function setStoredLang(l: Lang) {
  try { localStorage.setItem(KEY_LANG, l) } catch {}
  try { window.dispatchEvent(new CustomEvent(EVT)) } catch {}
}

// React hook: returns the current language and re-renders on change.
import { useEffect, useState } from 'react'
export function useLang(): Lang {
  const [l, setL] = useState<Lang>(getStoredLang)
  useEffect(() => {
    const on = () => setL(getStoredLang())
    window.addEventListener(EVT, on)
    return () => window.removeEventListener(EVT, on)
  }, [])
  return l
}

